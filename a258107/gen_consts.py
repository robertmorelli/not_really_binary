#!/usr/bin/env python3
"""Generate consts.h: high-precision constants for scan.c.

ALPHA_T[B][b] = frac(log_b(B)) * 2^256, floor, 4 little-endian 64-bit limbs.
LN_T[b]       = ln(b) * 2^192, floor, 4 little-endian limbs (top limb = integer part).
"""
from decimal import Decimal, getcontext

getcontext().prec = 160


def limbs(x):
    return ", ".join("0x%016xULL" % ((x >> (64 * i)) & (2**64 - 1)) for i in range(4))


out = ["/* generated by gen_consts.py -- do not edit */"]
out.append("static const u64 ALPHA_T[7][7][4] = {")
for B in range(7):
    out.append("  {")
    for b in range(7):
        if 4 <= B <= 6 and 3 <= b < B:
            r = Decimal(B).ln() / Decimal(b).ln()
            f = r - int(r)
            v = int(f * (1 << 256))
            assert 0 < v < 1 << 256
        else:
            v = 0
        out.append("    { %s }," % limbs(v))
    out.append("  },")
out.append("};")
out.append("static const u64 LN_T[7][4] = {")
for b in range(7):
    v = int(Decimal(b).ln() * (1 << 192)) if b >= 2 else 0
    out.append("  { %s }," % limbs(v))
out.append("};")
open("consts.h", "w").write("\n".join(out) + "\n")
print("wrote consts.h")
